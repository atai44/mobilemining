#!/usr/bin/env python3
"""Draws the app icon (pixel art: a white monkey in a miner's helmet) and writes every size.

    python3 scripts/make-icon.py
"""
import os
from PIL import Image

ROWS = """
................................
................................
............YYYYYYYY............
..........YYyyyyyyyyYY..........
.........YyyyyLLLLyyyyY.........
........YyyyyLWWWWLyyyyY........
........YyyyyLWWWWLyyyyY........
.......YyyyyyyLLLLyyyyyyY.......
.......YyyyyyyyyyyyyyyyyY.......
......DDDDDDDDDDDDDDDDDDDD......
.....DddddddddddddddddddddD.....
....EE.WWWWWWWWWWWWWWWWWW.EE....
...EeeEWWWWWWWWWWWWWWWWWWEeeE...
...EeeEWWBBBBBBWWBBBBBBWWEeeE...
...EeeEWBBBBBBBBBBBBBBBBWEeeE...
....EEWWBBOOOBBBBBBOOOBBWWEE....
......WWBBOKOBBBBBBOKOBBWW......
......WWBBOOOBBBBBBOOOBBWW......
......WWWBBBBBBNNBBBBBBWWW......
.......WWWBBBBBNNBBBBBWWW.......
.......WWWWWBBBBBBBBWWWWW.......
........WWWWWWMMMMWWWWWW........
........SWWWWWWWWWWWWWWS........
.........SWWWWWWWWWWWWS.........
..........SSWWWWWWWWSS..........
.........WWWSSSSSSSSWWW.........
........WWWWWWWWWWWWWWWW........
.......WWWWWWWWWWWWWWWWWW.......
.......WWWWWWWWWWWWWWWWWW.......
......SWWWWWWWWWWWWWWWWWWS......
......SWWWWWWWWWWWWWWWWWWS......
................................
""".strip().split('\n')

COLORS = {
    '.': (51, 102, 153),    # background (the app's blue)
    'Y': (201, 152, 26),    # helmet outline
    'y': (242, 194, 48),    # helmet
    'L': (120, 120, 120),   # lamp rim
    'W': (247, 244, 236),   # fur / lamp glass
    'S': (214, 208, 194),   # fur shadow
    'D': (150, 110, 15),    # helmet brim edge
    'd': (224, 172, 34),    # helmet brim
    'E': (74, 44, 26),      # ear outline
    'e': (150, 100, 70),    # inner ear
    'B': (110, 68, 40),     # face mask
    'O': (255, 255, 255),   # eye white
    'K': (20, 20, 20),      # pupil
    'N': (50, 30, 20),      # nose
    'M': (90, 50, 30),      # mouth
}

def base():
    n = len(ROWS)
    assert all(len(r) == n for r in ROWS), [len(r) for r in ROWS]
    im = Image.new('RGB', (n, n))
    im.putdata([COLORS[c] for r in ROWS for c in r])
    return im

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
icon = base()
up = lambda size: icon.resize((size, size), Image.NEAREST)
bg = COLORS['.']

# Web
for size in (192, 512):
    up(size).save(os.path.join(root, 'public/icons', f'icon-{size}.png'))
n = icon.width
rects = ''.join(f'<rect x="{x}" y="{y}" width="1" height="1" fill="#%02x%02x%02x"/>' % icon.getpixel((x, y)) for y in range(n) for x in range(n) if icon.getpixel((x, y)) != bg)
open(os.path.join(root, 'public/icons/icon.svg'), 'w').write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}" shape-rendering="crispEdges"><rect width="{n}" height="{n}" fill="#%02x%02x%02x"/>{rects}</svg>\n' % bg)

# Android: legacy icons, round icons, and the adaptive foreground (art in the middle 2/3)
res = os.path.join(root, 'android/app/src/main/res')
for d, s in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
    up(s).save(f'{res}/mipmap-{d}/ic_launcher.png')
    up(s).save(f'{res}/mipmap-{d}/ic_launcher_round.png')
    f = s * 108 // 48
    inner = (f * 2 // 3) // n * n or n
    fg = Image.new('RGB', (f, f), bg)
    fg.paste(icon.resize((inner, inner), Image.NEAREST), ((f - inner) // 2, (f - inner) // 2))
    fg.save(f'{res}/mipmap-{d}/ic_launcher_foreground.png')
open(f'{res}/values/ic_launcher_background.xml', 'w').write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#%02X%02X%02X</color>\n</resources>\n' % bg)
import glob
for p in glob.glob(f'{res}/drawable*/splash.png'):
    w, h = Image.open(p).size
    im = Image.new('RGB', (w, h), bg)
    s = (min(w, h) // 3) // n * n
    im.paste(icon.resize((s, s), Image.NEAREST), ((w - s) // 2, (h - s) // 2))
    im.save(p)
print('icon written')
